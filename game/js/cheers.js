// एक ही लाइन बार-बार नहीं: पिछली दो छोड़कर
const last = {};
export function pickCheer(kind, tier = -1) {
  const L = CHEERS[kind] || CHEERS.near;
  if (tier >= 0) return L[Math.min(tier, L.length - 1)];
  const recent = last[kind] || [];
  const pool = L.map((_, i) => i).filter((i) => !recent.includes(i));
  const i = pool[Math.floor(Math.random() * pool.length)] ?? 0;
  last[kind] = [i, ...recent].slice(0, Math.min(2, L.length - 1));
  return L[i];
}
